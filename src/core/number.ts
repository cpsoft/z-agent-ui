// 数值公共层：抹掉 IEEE754 的加法尾巴，以及「没配格式的数值」的默认呈现。
//
// [边界：只处理「产生噪声的地方」，不处理「呈现」] 这是本模块最关键的一条，
// 2026-11-14 核对时发现原注释写反了 —— 它说「三处各写一遍 toPrecision(12)」，
// 但实际只有两处调用，且**呈现层是刻意不截断的**：
//
//   · `cleanFloat` 的调用点只有两处：`page/data/dataset.ts` 的 aggregateRows 与
//     `report/core/report-group.ts` 的累加。那是本仓唯一做浮点加法的地方（issue IKQM8I）。
//   · `report-columns.formatCellValue` **明确不做**这件事，理由写在那边的注释里：
//     呈现层无法区分「真精度」与「累加尾巴」—— `24.681818181818183` 是数据本身的精度，
//     `131.80000000000004` 是 sum 产生的噪声，形态完全一样。在那里按位数截断会丢掉
//     真精度，且已有测试专门守着这条。
//
// 所以「同一份数据两个入口各说各话」这个症状，解法不是「让两边都截断」，
// 而是「在产生噪声的那一处截断一次」。本模块是那个「一处」。
//
// [WHY 12 位] 双精度有约 15-17 位有效数字；按 12 位截断足以抹掉 sum/avg 累积的
// `…0000004`，而业务上 12 位有效数字（万亿级金额到分）远未被触及。
// 这不是「四舍五入到两位」，只是**还原人算得出来的那个数**，所以它不该改变
// 任何显式配了小数位的列 —— 那些列由配置决定，不由这里决定。

/** 抹掉浮点噪声：`131.80000000000004` → `131.8`。非有限值原样返回。 */
export function cleanFloat(n: number): number {
  if (!Number.isFinite(n)) return n;
  // toPrecision 会返回字符串（可能带指数），Number 收回数值
  return Number(n.toPrecision(12));
}

/**
 * 「没有配格式」的数值该显示成什么：非数值原样 `String()`，数值先清噪声再 `String()`
 * （最短往返表示，不补零、不打千分位）。
 *
 * [现状：零调用，且接线方向未定] 2026-11-14 实测全仓无引用。它原本设想给
 * 「页面卡片未配格式的列」用，但格式化的决定权在 `report-columns`，而那边已经
 * 明确拒绝了在呈现层截断（见文件头）。所以**不要**把它直接接进 `formatCellValue` ——
 * 会丢真精度并撞上既有测试。
 *
 * 要接线，先回答一个问题：这个调用点是否也在做浮点加法？
 *   · 是 → 它该用 `cleanFloat`（在加法处清理），不是这个函数
 *   · 否 → 它显示的是原始数据，那就不该截断
 * 两个答案都指向「暂时不需要它」。保留是因为它是对外导出，删除属破坏性改动。
 */
export function plainNumberText(v: unknown): string {
  if (typeof v === "number") return String(cleanFloat(v));
  return String(v);
}
