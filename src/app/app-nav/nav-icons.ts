/**
 * 首字回落：未知图标名 / 未给图标时，用标题首字代替。
 *
 * [WHY 不画空白占位] 一个空方块会让人以为是「图标没加载完」，而首字是**可读的信息**：
 * 中文标题取第一个字，英文取前两位（与 `z-app-switcher` 的 initialOf 同一口径）。
 * 未知名字走这条而不是抛错 —— 图标名错一个字母不该让整个侧栏渲染不出来。
 */
export function initialOf(title: string): string {
  const t = (title || "").trim();
  if (!t) return "";
  return /[\u4e00-\u9fa5]/.test(t) ? t.slice(0, 1) : t.slice(0, 2).toUpperCase();
}
