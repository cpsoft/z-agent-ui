// 全树扫描型守卫的**时间预算**。
//
// [WHY 需要这个文件] vitest 默认 testTimeout = 5000ms，那是给「逻辑测试」定的。
// 但本仓库有一类守卫不测逻辑、测的是**仓库事实**：把 src/ 下几百个文件全读一遍再判
// （令牌引用、事件守恒、模块图注册……）。它们的耗时随仓库长大而线性增长，与代码质量无关。
//
// 2026-11-15 实测（`npx vitest run --maxWorkers=2`，581 个文件 / 5.0MB 源码）：
//   · 光是把 src/ 的 .ts+.css 读一遍就 2.3s —— 只读不判，这里没有优化空间；
//   · component-manifest-guard 反向用例 6.5s、demo-imports-guard ③ 7.0s、
//     theme-token-guard 裸 z-index 用例 12.1s，**全部超过 5s 而全部断言通过**。
// 也就是说：默认预算下这三条会红，而红的原因是「机器忙」，不是「仓库坏了」。
//
// 这类假红比假绿更伤：它训练人「红了先重跑」。所以给它们一个显式、宽到只在
// 真卡死时才触发的预算，并把测量数字留在这里 —— 下次有人发现 30s 也不够时，
// 该做的是**减少重复扫描**（见各文件里的读取缓存），而不是继续往上加。
//
// [WHY 不全局改 vitest.config] 全局放宽会把 4285 条普通逻辑测试的「挂死探测」
// 从 5s 变成 30s，而那才是默认值真正在保护的东西。宽预算只发给确实在扫盘的那几条。
export const SCAN_TIMEOUT_MS = 30_000;
